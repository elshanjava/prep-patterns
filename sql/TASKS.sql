-- ════════════════════════════════════════════════════════════════════════════════════════════════
--  13. Последняя запись по счёту (DISTINCT ON)
-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  ЗАДАЧА
--    Самая свежая транзакция каждого счёта.
--
--  ОТКУДА
--    transactions
--
--  ВЕРНУТЬ
--    account_id, id, amount, created_at
--
--  УСЛОВИЯ
--    - ровно одна строка на счёт — самая свежая
--    - DISTINCT ON (account_id): ORDER BY обязан НАЧИНАТЬСЯ с account_id, потом created_at
--      DESC, id DESC
