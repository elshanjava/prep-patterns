-- ════════════════════════════════════════════════════════════════════════════════════════════════
--  6. LAG: дельта с предыдущей
-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  ЗАДАЧА
--    Разница суммы с предыдущей транзакцией счёта.
--
--  ОТКУДА
--    transactions
--
--  ВЕРНУТЬ
--    id, amount, diff_prev
--
--  УСЛОВИЯ
--    - разница с предыдущей транзакцией ТОГО ЖЕ счёта
--    - порядок — по created_at, id
--    - у первой строки счёта предыдущей нет -> NULL
--    - эталон смотрит на account_id = 1006
--
--  ПОДСКАЗКА
--    У первой строки LAG = NULL → разница NULL. Нужен дефолт — LAG(amount,1,0).
-- ════════════════════════════════════════════════════════════════════════════════════════════════

select account_id, id,
       transactions.amount - lag(amount)
                             over (partition by transactions.account_id order by created_at, id) AS diff_prev
from transactions;

