-- ════════════════════════════════════════════════════════════════════════════════════════════════
--  1. Баланс пользователя (SETTLED)
-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  ЗАДАЧА
--    Сумма проведённых транзакций по всем счетам юзера.
--
--  ОТКУДА
--    users -> accounts -> transactions
--
--  ВЕРНУТЬ
--    u.id, u.name, settled_balance
--
--  УСЛОВИЯ
--    - считать только transactions.status = 'SETTLED'
--    - юзер со счетами, но без SETTLED-транзакций обязан остаться в выводе с нулём
--    - эталон берёт accounts внутренним JOIN — юзеры вообще без счетов (Ghost 1-3) не попадают
--
--  ПОДСКАЗКА
--    Фильтр по status — в ON, а не в WHERE: иначе LEFT JOIN схлопнется в INNER и юзеры без
--    SETTLED исчезнут.
-- ════════════════════════════════════════════════════════════════════════════════════════════════


select u.id, u.name, COALESCE(sum(t.amount), 0) AS settled_balance
            from users u
            join public.accounts a on u.id = a.user_id
            left join public.transactions t on a.id = t.account_id
                         and t.status = 'SETTLED'
    group by u.id, u.name;

-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  эталон 1
-- ────────────────────────────────────────────────────────────────────────────────────────────────
/*
