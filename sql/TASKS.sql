-- ════════════════════════════════════════════════════════════════════════════════════════════════
--  5. RANK vs DENSE_RANK
-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  ЗАДАЧА
--    Ранг счетов по балансу.
--
--  ОТКУДА
--    accounts
--
--  ВЕРНУТЬ
--    id, balance, rnk, dense_rnk
--
--  УСЛОВИЯ
--    - по убыванию balance
--    - зачёт общий — секций нет
--    - тай-брейк по id НЕ добавлять: с уникальным ключом ничьи исчезнут и обе функции совпадут
--    - единственная ничья в данных — счета 2001 и 2002 с балансом 0.00
--
--  ПОДСКАЗКА
--    RANK оставляет дыры после ничьих (1,1,3), DENSE_RANK — нет (1,1,2), ROW_NUMBER всегда
--    уникален.
-- ════════════════════════════════════════════════════════════════════════════════════════════════


select id, accounts.balance,
       rank() over (amount_rank),
       dense_rank() over (amount_rank),
       row_number() over (amount_rank)
from accounts
window amount_rank as (order by balance desc);

-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  эталон 5
-- ────────────────────────────────────────────────────────────────────────────────────────────────
/*
