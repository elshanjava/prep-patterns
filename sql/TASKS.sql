--  9. Percent of total
-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  ЗАДАЧА
--    Доля транзакции в обороте счёта.
--
--  ОТКУДА
--    transactions
--
--  ВЕРНУТЬ
--    id, amount, pct
--
--  УСЛОВИЯ
--    - доля |amount| в обороте своего счёта, в процентах
