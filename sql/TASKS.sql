-- ════════════════════════════════════════════════════════════════════════════════════════════════
--  8. Running balance
-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  ЗАДАЧА
--    Нарастающий баланс по счёту.
--
--  ОТКУДА
--    transactions
--
--  ВЕРНУТЬ
--    id, amount, running_balance
--
--  УСЛОВИЯ
--    - нарастающий итог внутри счёта, по возрастанию времени
--    - рамку писать явно: ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
--
--  ПОДСКАЗКА
--    SQL-аналог задачи, где в Java стрим был НЕ нужен (№34). Явный фрейм ROWS важен: RANGE при
--    равных ключах суммирует все ничьи разом.
-- ════════════════════════════════════════════════════════════════════════════════════════════════


select t.id, t.amount, SUM(amount) over (partition by account_id order by created_at, id ROWS BETWEEN UNBOUNDED PRECEDING
    AND CURRENT ROW) AS running_balance
from transactions t;

-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  эталон 8
-- ────────────────────────────────────────────────────────────────────────────────────────────────
/*
