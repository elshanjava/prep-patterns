--  4. ROW_NUMBER: нумерация по счёту
-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  ЗАДАЧА
--    Пронумеровать транзакции внутри счёта по времени.
--
--  ОТКУДА
--    transactions
--
--  ВЕРНУТЬ
--    account_id, id, amount, seq
--
--  УСЛОВИЯ
--    - нумерация внутри каждого счёта
--    - порядок — по created_at, вторым ключом id (в данных есть дубли по времени)
