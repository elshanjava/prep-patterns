-- ════════════════════════════════════════════════════════════════════════════════════════════════
--  10. NTILE: квартили
-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  ЗАДАЧА
--    Разбить юзеров на 4 корзины по обороту.
--
--  ОТКУДА
--    transactions -> accounts
--
--  ВЕРНУТЬ
--    user_id, vol, quartile
--
--  УСЛОВИЯ
--    - сначала свернуть оборот SUM(ABS(amount)) по user_id
--    - затем NTILE(4) по убыванию оборота: корзина 1 — крупнейшие
--    - юзеров с оборотом 500, пятеро без транзакций не попадают
--
--  ПОДСКАЗКА
--    NTILE делит максимально ровно; при неделящемся числе строк ранние корзины крупнее на 1.
-- ════════════════════════════════════════════════════════════════════════════════════════════════

WITH turnover AS (
    SELECT a.user_id, SUM(ABS(t.amount)) AS vol
    FROM transactions t
        JOIN accounts a ON a.id=t.account_id
    GROUP BY a.user_id)
SELECT user_id, vol,
       NTILE(4) OVER (ORDER BY vol DESC) AS quartile
FROM turnover;

-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  эталон 10
-- ────────────────────────────────────────────────────────────────────────────────────────────────
