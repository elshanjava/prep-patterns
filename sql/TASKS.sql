-- ════════════════════════════════════════════════════════════════════════════════════════════════
--  7. LEAD: время до следующей
-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  ЗАДАЧА
--    Интервал до следующей транзакции.
--
--  ОТКУДА
--    transactions
--
--  ВЕРНУТЬ
--    id, created_at, gap
--
--  УСЛОВИЯ
--    - интервал до СЛЕДУЮЩЕЙ транзакции того же счёта
--    - разность двух timestamptz даёт interval
--    - у последней строки счёта следующей нет -> NULL
--
--  ПОДСКАЗКА
--    Последняя строка партиции → LEAD NULL. Разница двух timestamptz даёт interval.
-- ════════════════════════════════════════════════════════════════════════════════════════════════

select id, created_at,
       lead(created_at) over (partition by transactions.account_id order by created_at, id) - transactions.created_at  AS gap
from transactions;

