-- ════════════════════════════════════════════════════════════════════════════════════════════════
--  3. Юзеры без единой транзакции
-- ────────────────────────────────────────────────────────────────────────────────────────────────
--  ЗАДАЧА
--    Ни одной транзакции ни по одному счёту.
--
--  ОТКУДА
--    users, accounts, transactions
--
--  ВЕРНУТЬ
--    u.id, u.name
--
--  УСЛОВИЯ
--    - ни одной транзакции ни по одному счёту
--    - сюда попадают и юзеры вообще без счетов (Ghost 1-3), и со счётом без транзакций (Idle
--      1-2)
--    - ожидается 5 строк
--
--  ПОДСКАЗКА
--    LEFT JOIN…IS NULL на уровне юзера ломается при нескольких счетах (уедет тот, у кого хоть
